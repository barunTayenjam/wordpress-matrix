#!/usr/bin/env bash
# site-types-lib.sh — multi-PHP-stack type registry for matrix.
# Spec: docs/superpowers/specs/2026-10-13-multi-php-stack-support-design.md
# Types, PHP floors, webroots, DB usage, runtime images, .matrix-type marker.

SITE_TYPES=(wp laravel symfony drupal joomla grav)

validate_site_type() {
    local type="${1:-}"
    case "$type" in
        wp|laravel|symfony|drupal|joomla|grav) return 0 ;;
        *) return 1 ;;
    esac
}

site_type_min_php() {
    local type="${1:-}"
    case "$type" in
        wp) echo "7.4" ;;
        joomla|grav) echo "8.1" ;;
        laravel|symfony) echo "8.2" ;;
        drupal) echo "8.3" ;;
        *) return 1 ;;
    esac
}

site_type_webroot() {
    local type="${1:-}"
    case "$type" in
        laravel|symfony) echo "public" ;;
        drupal) echo "web" ;;
        wp|joomla|grav) echo "" ;;
        *) return 1 ;;
    esac
}

site_type_uses_db() {
    local type="${1:-}"
    [[ "$type" == "grav" ]] && return 1
    validate_site_type "$type"
}

site_type_runtime_image() {
    local type="${1:-}" php="${2:-}"
    if [[ "$type" == "wp" ]]; then
        echo "wordpress:php${php}-fpm"
    else
        echo "matrix-php:${php}"
    fi
}

get_site_type() {
    local site="${1:-}"
    local marker="$PROJECT_ROOT/wp_${site}/.matrix-type"
    if [[ -f "$marker" ]]; then
        cat "$marker"
    else
        echo "wp"
    fi
}

set_site_type() {
    local site="${1:-}" type="${2:-}"
    validate_site_type "$type" || return 1
    echo "$type" > "$PROJECT_ROOT/wp_${site}/.matrix-type"
}

# php_at_least <have> <floor> — version-aware PHP floor comparison (sort -V)
php_at_least() {
    local have="${1:-}" floor="${2:-}"
    [[ "$(printf '%s\n' "$floor" "$have" | sort -V | head -1)" == "$floor" ]]
}

# Joomla 5 stable full-package zip. Floating minor; override via MATRIX_JOOMLA_URL.
joomla_zip_url() {
    echo "${MATRIX_JOOMLA_URL:-https://downloads.joomla.org/cms/joomla5/5.3/joomla_5-3-stable-full_package.zip}"
}

# provision_joomla <site> <php> — Joomla 5 zip + unzip into webroot.
# Configuration happens in Joomla's own first-visit wizard; DB creds are
# printed by create (compose DB env covers the container side).
provision_joomla() {
    local site="${1:-}" php="${2:-}"
    local dir="$PROJECT_ROOT/wp_${site}"
    local url
    url=$(joomla_zip_url)
    $CONTAINER_RUNTIME run --rm -v "$dir":/var/www/html "matrix-php:${php}" \
        bash -lc "curl -fsSL '$url' -o /tmp/joomla.zip && unzip -q /tmp/joomla.zip -d /var/www/html && rm /tmp/joomla.zip" \
        || return 1
    $CONTAINER_RUNTIME run --rm -v "$dir":/var/www/html "matrix-php:${php}" \
        chown -R www-data:www-data /var/www/html
}

# seed_drupal_settings <site> — pre-wire web/sites/default/settings.php so the
# Drupal wizard needs no typing (parity with WP's pre-wired DB).
seed_drupal_settings() {
    local site="${1:-}"
    local sd="$PROJECT_ROOT/wp_${site}/web/sites/default"
    [[ -d "$sd" ]] || mkdir -p "$sd"
    local salt
    salt=$(head -c 32 /dev/urandom | base64 | tr -d '=+/' | cut -c1-40)
    cat > "$sd/settings.php" <<PHPEOF
<?php
// Generated by matrix multi-stack provisioning
\$databases['default']['default'] = array (
  'driver' => 'mysql',
  'database' => '${site}_db',
  'username' => '${MYSQL_USER:-wp_user}',
  'password' => '${MYSQL_PASSWORD:-wp_password}',
  'host' => 'db',
  'prefix' => '',
);
\$settings['hash_salt'] = '${salt}';
PHPEOF
}

# rollback_site_create <site> — remove a half-provisioned site dir + logs after
# failed non-wp provisioning. Half-composer sites are useless (unlike WP where
# failures leave valid sites), so create rolls back instead of best-effort.
rollback_site_create() {
    local site="${1:-}"
    log_error "Provisioning failed for '$site' — rolling back"
    rm -rf "$PROJECT_ROOT/wp_${site}" "$PROJECT_ROOT/logs/wp_${site}"
}

# provision_site_type <site> <type> <php> — dispatcher for non-wp provisioning.
# wp is handled inline by create_site.
provision_site_type() {
    local site="${1:-}" type="${2:-}" php="${3:-}"
    case "$type" in
        laravel)
            provision_composer "$site" laravel "$php" || return 1
            seed_laravel_env "$site" || return 1
            ;;
        symfony)
            provision_composer "$site" symfony "$php" || return 1
            seed_symfony_env "$site" || return 1
            ;;
        drupal)
            provision_composer "$site" drupal "$php" || return 1
            seed_drupal_settings "$site" || return 1
            ;;
        grav)
            provision_composer "$site" grav "$php" || return 1
            ;;
        joomla)
            provision_joomla "$site" "$php" || return 1
            ;;
        wp) return 0 ;;
        *)
            log_error "provision_site_type: unsupported type $type"
            return 1
            ;;
    esac
}

# provision_composer <site> <type> <php> — one-shot matrix-php container runs
# composer create-project into the site dir. Site markers (.matrix-stack,
# .matrix-type) are written AFTER provisioning (create-project needs an empty
# target). Caller handles failure/rollback.
provision_composer() {
    local site="${1:-}" type="${2:-}" php="${3:-}"
    local dir="$PROJECT_ROOT/wp_${site}"
    local pkg
    case "$type" in
        laravel) pkg="laravel/laravel" ;;
        symfony) pkg="symfony/skeleton" ;;
        drupal)  pkg="drupal/recommended-project" ;;
        grav)    pkg="getgrav/grav" ;;
        *) log_error "provision_composer: unsupported type $type"; return 1 ;;
    esac
    $CONTAINER_RUNTIME run --rm -v "$dir":/var/www/html "matrix-php:${php}" \
        composer create-project "$pkg" /var/www/html --no-interaction --prefer-dist \
        || return 1
    $CONTAINER_RUNTIME run --rm -v "$dir":/var/www/html "matrix-php:${php}" \
        chown -R www-data:www-data /var/www/html
}

# seed_laravel_env <site> — patch the create-project generated .env with the
# platform DB creds. Replace-in-place; missing lines are laravel's defaults.
seed_laravel_env() {
    local site="${1:-}"
    local env="$PROJECT_ROOT/wp_${site}/.env"
    [[ -f "$env" ]] || return 0
    sed -i \
        -e 's|^DB_HOST=.*|DB_HOST=db|' \
        -e 's|^DB_PORT=.*|DB_PORT=3306|' \
        -e "s|^DB_DATABASE=.*|DB_DATABASE=${site}_db|" \
        -e "s|^DB_USERNAME=.*|DB_USERNAME=${MYSQL_USER:-wp_user}|" \
        -e "s|^DB_PASSWORD=.*|DB_PASSWORD=${MYSQL_PASSWORD:-wp_password}|" \
        "$env"
}

# seed_symfony_env <site> — point DATABASE_URL at the platform DB.
# ponytail: creds with | or & break sed — fine for local .env defaults; switch
# to a temp-file rewrite when a user sets exotic passwords.
seed_symfony_env() {
    local site="${1:-}"
    local env="$PROJECT_ROOT/wp_${site}/.env"
    [[ -f "$env" ]] || return 0
    local url="DATABASE_URL=\"mysql://${MYSQL_USER:-wp_user}:${MYSQL_PASSWORD:-wp_password}@db:3306/${site}_db\""
    if grep -q '^DATABASE_URL=' "$env"; then
        sed -i "s|^DATABASE_URL=.*|$url|" "$env"
    else
        printf '%s\n' "$url" >> "$env"
    fi
}

# build_site_image <php> — build matrix-php:<php> only when not present.
# Mirrors matrix_site_build_if_apache: image build is idempotent per version.
build_site_image() {
    local php="${1:-}"
    local image="matrix-php:${php}"
    if [[ -n "$($CONTAINER_RUNTIME images -q "$image" 2>/dev/null)" ]]; then
        return 0
    fi
    $CONTAINER_RUNTIME build --build-arg PHP_VERSION="$php" -t "$image" \
        "$PROJECT_ROOT/config/docker/php-site"
}

# generate_nginx_conf <site> <type> — write config/nginx/<site>.conf with the
# type's webroot. Extracted from create_site's inline heredoc (multi-stack spec).
generate_nginx_conf() {
    local site="${1:-}"
    local type="${2:-wp}"
    local webroot
    webroot=$(site_type_webroot "$type")
    [[ -n "$webroot" ]] && webroot="/${webroot}"
    local conf_dir="$PROJECT_ROOT/config/nginx"
    [[ -d "$conf_dir" ]] || mkdir -p "$conf_dir"
    cat > "$conf_dir/$site.conf" << EOF
server {
    listen 80;
    server_name _;
    root /var/www/html${webroot};
    index index.php index.html;
    client_max_body_size 25m;

    location / {
        try_files \$uri \$uri/ /index.php?\$query_string;
    }

    location ~ \.php\$ {
        fastcgi_pass wp_$site:9000;
        fastcgi_index index.php;
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        include fastcgi_params;

        # Increase buffer sizes to handle large headers
        fastcgi_buffer_size 32k;
        fastcgi_buffers 16 16k;
        fastcgi_busy_buffers_size 32k;
    }

    # Deny access to sensitive files
    location ~ /\. {
        deny all;
    }
}
EOF
}
